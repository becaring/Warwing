"""Generate the console ROM extractor's entry table from the pinned Torch YAMLs.

Each archive name is the YAML file stem and entry name, as Torch writes them. Reloc
entries carry their file ID; blobs carry their ROM offset and size. The table feeds
platform/xbox360/cpp-compat/startup/rom_archive.cpp.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
YAMLS = ROOT / "upstream/BattleShip/yamls/us"
OUT = ROOT / "scratch/rom-archive/rom_entries.cpp"


def entries(folder=YAMLS):
    rows = []
    for path in sorted(folder.glob("*.yml")):
        for name, body in re.findall(r"^([A-Za-z0-9_]+):\n((?:[ \t]+.*\n?|\n)*)", path.read_text(encoding="utf-8"), re.M):
            fields = dict(re.findall(r"^  (\w+): *([^\s#]+)", body, re.M))
            kind = fields["type"]
            if kind == "SSB64:RELOC":
                rows.append((path.stem + "/" + name, int(fields["file_id"], 0), 0, 0))
            elif kind == "BLOB":
                rows.append((path.stem + "/" + name, -1, int(fields["offset"], 0), int(fields["size"], 0)))
            else:
                raise ValueError("Unsupported Torch entry type %s in %s" % (kind, path.name))
    if len(set(row[0] for row in rows)) != len(rows):
        raise ValueError("Duplicate Torch entry names")
    return rows


def generate(out=OUT, folder=YAMLS):
    lines = [
        "// Generated by tools/rom_entries.py from upstream/BattleShip/yamls/us; do not edit.",
        '#include "startup/rom_archive.h"',
        "",
        "namespace Smash360Startup {",
        "const RomEntry kRomEntries[] = {",
    ]
    rows = entries(folder)
    lines += ['    { "%s", %d, 0x%Xu, 0x%Xu },' % row for row in rows]
    lines += ["};", "const size_t kRomEntryCount = sizeof(kRomEntries) / sizeof(kRomEntries[0]);", "} // namespace Smash360Startup", ""]
    text = "\n".join(lines)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.is_file() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8", newline="\n")
    return len(rows)


if __name__ == "__main__":
    print("%d ROM entries -> %s" % (generate(), OUT))
